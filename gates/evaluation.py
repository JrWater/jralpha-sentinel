"""The one module that evaluates gates for a typed subject.

Callers provide a ``CycleSubject`` or ``ProposalSubject``. This module alone
constructs ``EvalContext`` and selects the gates that accept that exact type.
Exact matching is deliberate: a proposal is-a cycle subject for data reuse,
but it must not re-run cycle gates and duplicate their findings.
"""
from __future__ import annotations

import subprocess
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from gates.registry import GateResult

ROOT = Path(__file__).resolve().parents[1]
GENERATED_PUBLIC_RECORDS = frozenset({"docs/snapshot.json"})


@dataclass
class EvalContext:
    """All facts gate checks are allowed to observe.

    Gate checks receive this internal context; callers receive the much smaller
    typed subject interface below. Missing facts remain ``None`` and checks
    fail closed.
    """

    manifest: Any
    now_utc: datetime
    account: Any = None
    is_paper_session: bool | None = None
    clock: Any = None
    positions: list = None
    ledger_positions: list | None = None
    option_quote_age_seconds: float | None = None
    underlying_bar_age_seconds: float | None = None
    decision_log_writable: bool | None = None
    git_head: str | None = None
    git_dirty: bool | None = None
    proposal: Any = None
    unresolved_dispatch_count: int | None = None
    unresolved_structure_close_count: int | None = None
    unresolved_entry_reconciliation_count: int | None = None

    def __post_init__(self):
        if self.positions is None:
            self.positions = []


@dataclass(frozen=True)
class CycleSubject:
    """Facts shared by all cycle-level readiness gates."""

    manifest: Any
    state: Any
    ledger_positions: list
    is_paper_session: bool = True
    decision_log_writable: bool | None = None
    git_head: str | None = None
    git_dirty: bool | None = None
    unresolved_dispatch_count: int | None = None
    unresolved_structure_close_count: int | None = None
    unresolved_entry_reconciliation_count: int | None = None


@dataclass(frozen=True)
class ProposalSubject(CycleSubject):
    """One proposed entry plus the cycle facts it is evaluated against."""

    proposal: Any = None

    @classmethod
    def from_cycle(cls, cycle: CycleSubject, proposal: Any) -> "ProposalSubject":
        return cls(
            manifest=cycle.manifest,
            state=cycle.state,
            ledger_positions=cycle.ledger_positions,
            is_paper_session=cycle.is_paper_session,
            decision_log_writable=cycle.decision_log_writable,
            git_head=cycle.git_head,
            git_dirty=cycle.git_dirty,
            unresolved_dispatch_count=cycle.unresolved_dispatch_count,
            unresolved_structure_close_count=cycle.unresolved_structure_close_count,
            unresolved_entry_reconciliation_count=(
                cycle.unresolved_entry_reconciliation_count),
            proposal=proposal,
        )


def code_identity(root: Path = ROOT) -> tuple[str | None, bool | None]:
    """The code identity shared by permits, snapshots, and gate contexts.

    ``docs/snapshot.json`` is evidence generated by each cycle, not running
    code.  Counting that one file as a code edit would make a clean release
    permanently appear dirty immediately after it reports its own result.
    All other tracked and untracked paths remain part of the identity check.
    """
    try:
        head = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=str(root),
            capture_output=True, text=True, timeout=10, check=True,
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain"], cwd=str(root),
            capture_output=True, text=True, timeout=10, check=True,
        ).stdout.splitlines()
        dirty = any(line[3:] not in GENERATED_PUBLIC_RECORDS
                    for line in status)
        return head, dirty
    except (OSError, subprocess.SubprocessError):
        return None, None


def _underlying_bar_age(state: Any) -> float | None:
    quote = getattr(state, "latest", {}).get("SPY")
    timestamp = getattr(quote, "timestamp", None)
    if timestamp is None:
        return None
    if timestamp.tzinfo is None:
        timestamp = timestamp.replace(tzinfo=timezone.utc)
    return max(0.0, (state.now_utc - timestamp).total_seconds())


def _decisions_writable(root: Path = ROOT) -> bool:
    path = root / "state" / "decisions.jsonl"
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a"):
            pass
        return True
    except OSError:
        return False


def _unresolved_dispatch_count(journal_view: Any) -> int | None:
    if journal_view is None or not getattr(journal_view, "integrity_ok", False):
        return None
    return len(getattr(journal_view, "unresolved_dispatches", ()))


class GateEvaluator:
    """Deep interface for gate dispatch and context construction."""

    def __init__(self, *, gates=None, root: Path = ROOT):
        self._gates = gates
        self._root = root

    @property
    def gates(self):
        if self._gates is None:
            from gates.checks import GATES
            return GATES
        return self._gates

    def cycle_subject(self, *, state: Any, manifest: Any, ledger_positions: list,
                      journal_view: Any, is_paper_session: bool = True,
                      unresolved_structure_close_count: int | None = None,
                      unresolved_entry_reconciliation_count: int | None = None
                      ) -> CycleSubject:
        head, dirty = code_identity(self._root)
        return CycleSubject(
            manifest=manifest, state=state, ledger_positions=ledger_positions,
            is_paper_session=is_paper_session,
            decision_log_writable=_decisions_writable(self._root),
            git_head=head, git_dirty=dirty,
            unresolved_dispatch_count=_unresolved_dispatch_count(journal_view),
            unresolved_structure_close_count=unresolved_structure_close_count,
            unresolved_entry_reconciliation_count=(
                unresolved_entry_reconciliation_count),
        )

    def proposal_subject(self, cycle: CycleSubject, proposal: Any) -> ProposalSubject:
        return ProposalSubject.from_cycle(cycle, proposal)

    def evaluate(self, subject: CycleSubject | ProposalSubject) -> dict[str, GateResult]:
        context = self._context(subject)
        return {
            gate.name: gate.check(context)
            for gate in self.gates
            if gate.accepts is type(subject)
        }

    @staticmethod
    def _context(subject: CycleSubject | ProposalSubject) -> EvalContext:
        state = subject.state
        proposal = subject.proposal if type(subject) is ProposalSubject else None
        quote_age = None
        if proposal is not None:
            # Malformed proposals are gate refusals, not evaluator crashes.
            # The specific proposal gate can explain the missing field; data
            # readiness remains unknown rather than silently defaulting to SPY.
            underlying = getattr(proposal, "underlying", None)
            if underlying:
                quote_age = getattr(state, "chain_ages", {}).get(underlying)
        return EvalContext(
            manifest=subject.manifest, now_utc=state.now_utc,
            account=state.account, is_paper_session=subject.is_paper_session,
            clock=state.clock, positions=state.positions,
            ledger_positions=subject.ledger_positions,
            option_quote_age_seconds=quote_age if quote_age is not None else
            getattr(state, "chain_ages", {}).get("SPY"),
            underlying_bar_age_seconds=_underlying_bar_age(state),
            decision_log_writable=subject.decision_log_writable,
            git_head=subject.git_head, git_dirty=subject.git_dirty,
            proposal=proposal,
            unresolved_dispatch_count=subject.unresolved_dispatch_count,
            unresolved_structure_close_count=subject.unresolved_structure_close_count,
            unresolved_entry_reconciliation_count=(
                subject.unresolved_entry_reconciliation_count),
        )


def phase_for(accepts: type) -> str:
    """Compatibility projection for public snapshots, derived not declared."""
    if accepts is CycleSubject:
        return "preflight"
    if accepts is ProposalSubject:
        return "pretrade"
    return "unknown"
